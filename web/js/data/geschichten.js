//   abStufe   ab welcher Hafenstufe (Stufe 1 und 2 liegen am See, ab 3 geht es zur Ostsee)
//   arten     optional: nur diese Bootsarten (kind aus data/boat-catalog.js)
//   segel / motor  optional true: nur Segel- bzw. Motorboote
//   braucht   optional { service: id } oder { bauwerk: id }: kommt nur vor, wenn es gebaut ist
