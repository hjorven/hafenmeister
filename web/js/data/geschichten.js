//   vorabend  optional: nur am Tag vor diesem Ereignistag (Regatta: anreisen, am Morgen auslaufen)
//   regatta   optional true: fährt an jedem Regattatag morgens hinaus zur Bahn (events/regatta-feld.js)
//   wunsch    optional: dieser Wunsch ist sicher dabei (wenn die Stufe ihn kennt)
//   landgang  Ziele an Land (Arten aus data/people.js ZIELE) mit Vorliebe-Faktor, 'ort' = in den Ort
//   gepaeck   optional 'aus' | 'ein' | 'wechsel': Leute mit Taschen gehen von Bord / kommen dazu
//   texte     Sätze für die Bootskarte, {nach} = Ziel, {detail} = eines aus details (die Herkunft steht
